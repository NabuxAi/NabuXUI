/**
 * The Vue panel's language layer — the pattern of apps/admin/src/lang.tsx, as a
 * plain module: a `Lang` union, a typed dictionary with **every** key of every
 * page (fa defines the shape, en fills the same shape), and a saved pick in
 * localStorage. Pages consume `s` from ./store and never edit this file; the
 * few words the hand-written components say themselves (close, menu, the kanban
 * moves…) come from the core i18n table via `translate()`.
 */

export type Lang = 'fa' | 'en';

export const LANG_KEY = 'nabuxui.admin.lang';

/** Saved pick — localStorage first, safe default when storage is closed. */
export function readLang(): Lang {
  try {
    return localStorage.getItem(LANG_KEY) === 'en' ? 'en' : 'fa';
  } catch {
    return 'fa';
  }
}

/** `'#1248'` → `'#۱۲۴۸'` in fa — seeded ids follow the panel language's digits. */
export function localeId(value: string, lang: Lang): string {
  return lang === 'fa' ? value.replace(/[0-9]/g, (digit) => '۰۱۲۳۴۵۶۷۸۹'[Number(digit)]) : value;
}

