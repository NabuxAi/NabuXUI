<?php

namespace App\Livewire;

use App\Livewire\Concerns\SwitchesDemoLocale;
use App\Support\DemoCatalog;
use App\Support\UseCases;
use Illuminate\Support\Facades\Http;
use Livewire\Attributes\Layout;
use Livewire\Component;

/**
 * /ai — the NabuGate studio: the user says what they are building ("یک فرم
 * ثبت‌نام با کد تأیید"), the request goes to NabuGate (the product's LLM
 * gateway) and the answer renders as a live, sandboxed draft next to the real
 * demos that serve the same purpose. Without a configured gateway the studio
 * stays honest about it and falls back to the local intent engine: the same
 * keyword scoring picks a use case and serves one of the twelve hand-built
 * recipes — composed from the very components the demos showcase.
 */
#[Layout('layouts.app')]
class AiStudio extends Component
{
    use SwitchesDemoLocale;

    /** The free-form "what am I building" prompt. */
    public string $prompt = '';

    /** Pre-picked use case (chip), or '' to let the engine score the prompt. */
    public string $usecase = '';

    /** null until the first generation; shape in self::RESULT below. */
    public ?array $result = null;

    /** How many drafts this session asked for — the prompt placeholder cycles. */
    public int $asked = 0;

    public function mount(): void
    {
        $this->rememberLocale();
    }

    public function updatedPrompt(): void
    {
        // A new question invalidates the previous draft.
        $this->result = null;
    }

    /**
     * The draft the studio hands back: which use case matched, the rendered
     * recipe (local) or the gateway's HTML (nabugate), the real demos that
     * serve the same purpose and the provider line shown under the preview.
     * shape: {mode: 'nabugate'|'local', bucket: string, recipe: ?string,
     *         html: ?string, name: string, description: string,
     *         demos: array<int, array{group,slug,title}>, provider: string}
     */
    public function generate(): void
    {
        $this->validate(['prompt' => 'required|string|min:3|max:500']);
        $this->asked++;

        $locale = app()->getLocale();
        $bucketId = $this->usecase !== '' ? $this->usecase : $this->matchBucket($this->prompt);
        $bucket = UseCases::find($bucketId) ?? UseCases::find('landing');
        $demos = $this->matchedDemos($bucket, $this->prompt);

        $gateway = $this->askNabuGate($bucket, $locale);
        if ($gateway !== null) {
            $this->result = [
                'mode' => 'nabugate',
                'bucket' => $bucket['id'],
                'recipe' => null,
                'html' => $gateway['html'],
                'name' => $gateway['name'] ?? DemoCatalog::pick($bucket['label'], $locale),
                'description' => $gateway['description'] ?? DemoCatalog::pick($bucket['description'], $locale),
                'demos' => $demos,
                'provider' => $locale === 'fa'
                    ? 'تولیدشده توسط نابوگیت — پیش‌نمایش در قاب ایزوله'
                    : 'Generated by NabuGate — previewed in a sandboxed frame',
            ];

            return;
        }

        $this->result = [
            'mode' => 'local',
            'bucket' => $bucket['id'],
            'recipe' => 'ai.recipes.'.$bucket['id'],
            'html' => null,
            'name' => DemoCatalog::pick($bucket['label'], $locale),
            'description' => DemoCatalog::pick($bucket['description'], $locale),
            'demos' => $demos,
            'provider' => config('services.nabugate.endpoint') === null
                ? ($locale === 'fa'
                    ? 'نابوگیت وصل نیست — پیش‌نویس محلی از موتور قصد، سرهم‌شده از همان کامپوننت‌ها'
                    : 'NabuGate is not connected — a local intent-engine draft, assembled from the same components')
                : ($locale === 'fa'
                    ? 'نابوگیت پاسخ نداد — پیش‌نویس محلی جایگزین شد'
                    : 'NabuGate did not answer — the local draft took over'),
        ];
    }

    /** Score every bucket's keywords against the folded prompt; best wins. */
    private function matchBucket(string $prompt): string
    {
        $folded = mb_strtolower($prompt);
        $best = 'landing';
        $bestScore = 0;
        foreach (UseCases::all() as $bucket) {
            $score = 0;
            foreach ($bucket['keywords'] as $keyword) {
                if (str_contains($folded, mb_strtolower($keyword))) {
                    $score++;
                }
            }
            if ($score > $bestScore) {
                $bestScore = $score;
                $best = $bucket['id'];
            }
        }

        return $best;
    }

    /** The catalog demos (inside the bucket's groups) whose text matches the prompt, best first. */
    private function matchedDemos(array $bucket, string $prompt): array
    {
        $locale = app()->getLocale();
        $groups = array_fill_keys($bucket['groups'], true);
        $keywords = array_map(fn (string $k) => mb_strtolower($k), $bucket['keywords']);
        $promptWords = preg_split('/[\s،,;.]+/u', mb_strtolower($prompt)) ?: [];
        $promptWords = array_filter($promptWords, fn (string $w) => mb_strlen($w) >= 3);

        $scored = [];
        foreach (DemoCatalog::flat() as $demo) {
            if (! isset($groups[$demo['group']])) {
                continue;
            }
            $haystack = mb_strtolower(implode(' ', [
                DemoCatalog::both($demo['title'] ?? ''),
                DemoCatalog::both($demo['oneLiner'] ?? ''),
                $demo['slug'] ?? '',
            ]));
            $score = 0;
            foreach ($keywords as $keyword) {
                if (str_contains($haystack, $keyword)) {
                    $score += 2;
                }
            }
            foreach ($promptWords as $word) {
                if ($word !== '' && str_contains($haystack, $word)) {
                    $score++;
                }
            }
            if ($score > 0) {
                $scored[] = ['score' => $score, 'demo' => $demo];
            }
        }
        usort($scored, fn (array $a, array $b) => $b['score'] <=> $a['score']);

        return array_map(fn (array $row) => [
            'group' => $row['demo']['group'],
            'slug' => $row['demo']['slug'],
            'title' => DemoCatalog::pick($row['demo']['title'] ?? '', $locale),
        ], array_slice($scored, 0, 4));
    }

    /**
     * The real gateway call. NabuGate is the product's own LLM gateway, so the
     * request/response shape is ours to define: send the prompt, the locale and
     * the palette of nx components; expect {name, description, html} back.
     * Anything missing or failing returns null and the local draft takes over.
     *
     * @return array{name?: string, description?: string, html: string}|null
     */
    private function askNabuGate(array $bucket, string $locale): ?array
    {
        $endpoint = config('services.nabugate.endpoint');
        $key = config('services.nabugate.key');

        if (! is_string($endpoint) || $endpoint === '') {
            return null;
        }

        try {
            $response = Http::timeout(24)
                ->when(is_string($key) && $key !== '', fn ($http) => $http->withToken($key))
                ->post($endpoint, [
                    'model' => config('services.nabugate.model', 'nabugate-1'),
                    'locale' => $locale,
                    'intent' => $bucket['id'],
                    'prompt' => $this->prompt,
                    'components' => 'NabuXUI nx-* Blade components on the shared @nabuxai/ui-core CSS; reply with a single self-contained HTML fragment, inline styles only, both light and dark safe.',
                ]);
        } catch (\Throwable) {
            return null;
        }

        if (! $response->successful()) {
            return null;
        }

        $payload = $response->json();
        $html = is_array($payload) ? ($payload['html'] ?? null) : null;

        return is_string($html) && trim($html) !== ''
            ? ['name' => $payload['name'] ?? null, 'description' => $payload['description'] ?? null, 'html' => $html]
            : null;
    }

    public function render()
    {
        return view('livewire.ai-studio', [
            'usecases' => UseCases::all(),
            'gatewayOn' => config('services.nabugate.endpoint') !== null,
        ]);
    }
}
