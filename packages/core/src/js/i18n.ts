export type Locale = keyof typeof messages;
export type MessageKey = keyof (typeof messages)['en'];

/** The language a subtree speaks, from the nearest `lang` attribute. */
export function localeOf(el?: Element | null): Locale {
  const lang = (el?.closest('[lang]')?.getAttribute('lang') ?? (typeof document !== 'undefined' ? document.documentElement.lang : '') ?? '').toLowerCase();
  if (lang.startsWith('fa')) return 'fa';
  if (lang.startsWith('ar')) return 'ar';
  return 'en';
}

export function translate(locale: Locale | string, key: MessageKey, params: Record<string, string | number> = {}): string {
  const table = (messages as Record<string, Record<string, string>>)[locale] ?? messages.en;
  const text = table[key] ?? messages.en[key];
  return text.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`));
}
