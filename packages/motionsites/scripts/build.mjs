#!/usr/bin/env node
/**
 * Generates the host-side indexes of the MotionSites scenes from
 * catalog.json + meta/{slug}.json + scenes/{slug}.html:
 *
 *   playground/app/Support/Demos/Ms-*.php   — one DemoCatalog manifest per group
 *   apps/showcase/src/motionsites/index.json — the showcase gallery index
 *
 * Only entries whose scene AND meta both exist are emitted, so the catalogs
 * grow as scenes land. Re-run after adding or editing any scene:
 *
 *   node packages/motionsites/scripts/build.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const PKG = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REPO = path.resolve(PKG, '../..');
const DEMOS = path.join(REPO, 'playground/app/Support/Demos');
const SHOWCASE = path.join(REPO, 'apps/showcase/src/motionsites');

export const GROUPS = {
  'ms-landing': { fa: 'موشن‌سایتس · لندینگ‌ها', en: 'MotionSites · Landing pages', icon: 'layers' },
  'ms-sections': { fa: 'موشن‌سایتس · بخش‌ها', en: 'MotionSites · Sections', icon: 'grid' },
  'ms-horizonx': { fa: 'موشن‌سایتس · هورایزن‌ایکس سه‌بعدی', en: 'MotionSites · HorizonX 3D', icon: 'cpu' },
  'ms-21st': { fa: 'موشن‌سایتس · رجیستری 21st.dev', en: 'MotionSites · 21st.dev registry', icon: 'command' },
  'ms-superdesign': { fa: 'موشن‌سایتس · سوپردیزاین', en: 'MotionSites · Superdesign', icon: 'sparkles' },
};

const catalog = JSON.parse(fs.readFileSync(path.join(PKG, 'catalog.json'), 'utf8'));

const ready = [];
const problems = [];
for (const entry of catalog) {
  const scene = path.join(PKG, 'scenes', `${entry.slug}.html`);
  const metaFile = path.join(PKG, 'meta', `${entry.slug}.json`);
  if (!fs.existsSync(scene) || !fs.existsSync(metaFile)) continue;
  let meta;
  try {
    meta = JSON.parse(fs.readFileSync(metaFile, 'utf8'));
  } catch (error) {
    problems.push(`${entry.slug}: invalid meta (${error.message})`);
    continue;
  }
  if (!meta.title?.en || !meta.title?.fa || !meta.oneLiner?.en || !meta.oneLiner?.fa) {
    problems.push(`${entry.slug}: meta needs title + oneLiner in en and fa`);
    continue;
  }
  ready.push({ entry, meta });
}

/** A PHP single-quoted string literal. */
const q = (value) => `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const pair = (value) => `['fa' => ${q(value?.fa ?? value?.en ?? '')}, 'en' => ${q(value?.en ?? '')}]`;

fs.mkdirSync(DEMOS, { recursive: true });
for (const [group, label] of Object.entries(GROUPS)) {
  const items = ready.filter(({ entry }) => entry.group === group);
  const file = path.join(DEMOS, `${group[0].toUpperCase()}${group.slice(1)}.php`);
  const lines = [
    '<?php',
    '',
    '/**',
    ` * GENERATED by packages/motionsites/scripts/build.mjs — do not edit by hand.`,
    ` * The "${label.en}" group: MotionSites prompts ported to live NabuXUI scenes.`,
    ' * Each entry\'s `scene` points at packages/motionsites/scenes/{slug}.html,',
    ' * which the demo page shows in a sandboxed iframe (see App\\Support\\MotionSites).',
    ' */',
    'return [',
    `    '__group' => ['fa' => ${q(label.fa)}, 'en' => ${q(label.en)}],`,
  ];
  for (const { entry, meta } of items) {
    lines.push('', `    ${q(entry.slug)} => [`);
    lines.push(`        'title' => ${pair(meta.title)},`);
    lines.push(`        'icon' => ${q(meta.icon || label.icon)},`);
    lines.push(`        'oneLiner' => ${pair(meta.oneLiner)},`);
    lines.push(`        'js' => ${meta.js === false ? 'false' : 'true'},`);
    lines.push(`        'docs' => ${q(entry.registry ? entry.registry.replace(/^https:\/\/21st\.dev\/r\/([^/]+)\/(.+)$/, 'https://21st.dev/@$1/components/$2') :'https://motionsitesai-main.vercel.app')},`);
    lines.push(`        'scene' => ${q(entry.slug)},`);
    const props = Array.isArray(meta.props) ? meta.props : [];
    if (props.length) {
      lines.push(`        'props' => [`);
      for (const prop of props) {
        lines.push(`            ['name' => ${q(prop.name ?? '')}, 'type' => ${q(prop.type ?? '')}, 'default' => ${q(prop.default ?? '—')}, 'note' => ${pair(prop.note ?? {})}],`);
      }
      lines.push('        ],');
    }
    lines.push('    ],');
  }
  lines.push('];', '');
  fs.writeFileSync(file, lines.join('\n'));
}

fs.mkdirSync(SHOWCASE, { recursive: true });
const index = ready.map(({ entry, meta }) => ({
  slug: entry.slug,
  group: entry.group,
  title: { fa: meta.title.fa, en: meta.title.en },
  oneLiner: { fa: meta.oneLiner.fa, en: meta.oneLiner.en },
  js: meta.js !== false,
  thumb: fs.existsSync(path.join(PKG, 'thumbs', `${entry.slug}.webp`)),
}));
fs.writeFileSync(path.join(SHOWCASE, 'index.json'), JSON.stringify({ groups: GROUPS, items: index }) + '\n');

const counts = Object.keys(GROUPS).map((g) => `${g} ${index.filter((i) => i.group === g).length}/${catalog.filter((c) => c.group === g).length}`);
console.log(`motionsites: ${index.length}/${catalog.length} scenes ready — ${counts.join(' · ')}`);
for (const problem of problems) console.warn(`  ! ${problem}`);
